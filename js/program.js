export const ALL_IDS = [];
WEEKS.forEach((w, i) => {
  w.n = i + 1;
  w.ids = w.tasks.map((_, j) => `w${w.n}-${j}`);
  w.ids.push(`w${w.n}-g`);
  ALL_IDS.push(...w.ids);
});
export const VALID = new Set(ALL_IDS);

export function weekOf(id){
  const m = /^w(\d+)-/.exec(id);
  return m ? WEEKS[Number(m[1]) - 1] : null;
}

export function itemText(id){
  const w = weekOf(id);
  if (!w) return "";
  const k = id.split("-")[1];
  return k === "g" ? w.geo : w.tasks[Number(k)] || "";
}

export function weekStart(n){ const d = new Date(START); d.setDate(d.getDate() + (n - 1) * 7); return d; }
export function fmtRange(n){
  const a = weekStart(n), b = new Date(a); b.setDate(b.getDate() + 6);
  if (a.getMonth() === b.getMonth()) return `${a.getDate()}–${b.getDate()} ${MONTHS[b.getMonth()]}`;
  return `${a.getDate()} ${MONTHS[a.getMonth()]} – ${b.getDate()} ${MONTHS[b.getMonth()]}`;
}
export function currentWeek(){
  const t = new Date(); t.setHours(0,0,0,0);
  const days = Math.round((t - START) / 864e5);
  if (days < 0) return {n:1, before:true};
  const n = Math.floor(days / 7) + 1;
  if (n > WEEKS.length) return {n:WEEKS.length, after:true};
  return {n};
}
export function todayISO(){
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
export function fmtISO(iso, withYear){
  const p = iso.split("-");
  return p[2] + "." + p[1] + (withYear ? "." + p[0] : "");
}
export const pad2 = (n) => String(n).padStart(2, "0");
